@pytest.mark.slow
def test_softening_respected():
    """The optimiser must not be allowed to exploit the P2P singularity.

    Position gradients of the near-field term scale like ``1 / r^3``, so a pair
    driven inside the softening length produces an enormous gradient and a
    meaningless field. This starts a pair at a twentieth of the softening length
    -- close enough that an unregularised fit has every incentive to keep it
    there -- and checks the regularised fit pushes it back out.

    The comparison against an unregularised run on the *same* start is the
    point: it is what makes this a statement about the regulariser rather than
    about the data term happening to be benign.
    """
    config, truth = _truth(128, 64)
    operator = _operator(config, truth)
    parameterization = make_parameterization("positions", config=config)

    start = np.array(truth.source_positions, dtype=np.float64)
    # Put the pair in the same leaf by construction: coincident-then-separated
    # particles land together in any partition built from these positions.
    start[1] = start[0] + np.array([SOFTENING / 20.0, 0.0, 0.0])
    assert _min_pair_distance(start) < 0.1 * SOFTENING

    def fit(regularization, iterations=60):
        return run_fit(
            operator=operator,
            observed=truth.observed_accelerations,
            parameterization=parameterization,
            initial_params=parameterization.pack(start),
            config=FitConfig(
                num_iterations=iterations,
                learning_rate=1.0e-3,
                rebuild_cadence=iterations,
                jit_within_epoch=True,
                regularization=regularization,
                history_every=iterations,
            ),
        )

    regularized = fit(Regularization(softening_floor=1.0e3, spacing_smoothness=0.0))
    unregularized = fit(Regularization.none())

    separation_regularized = _min_pair_distance(regularized.positions)
    separation_unregularized = _min_pair_distance(unregularized.positions)

    # The regulariser opened the pair up by at least an order of magnitude on
    # the run that was paying for it ...
    assert separation_regularized > 10.0 * (SOFTENING / 20.0), (
        f"regularised fit left the pair at {separation_regularized:.3e}, "
        f"floor is {SOFTENING:.3e}"
    )
    # ... to a stated fraction of the softening length ...
    assert separation_regularized > 0.5 * SOFTENING
    # ... and did so *because* of the regulariser, not despite it.
    assert separation_regularized > 5.0 * separation_unregularized, (
        f"regularised {separation_regularized:.3e} vs unregularised "
        f"{separation_unregularized:.3e}: the term is not doing the work"
    )

    # The penalty itself fell, and is reported even by the run that paid nothing.
    assert (
        regularized.history[-1]["components"]["softening_floor"]
        < unregularized.history[-1]["components"]["softening_floor"]
    )
    assert (
        "softening_floor" in unregularized.history[-1]["components"]
    ), "an unregularised run must still report what it was not paying"
