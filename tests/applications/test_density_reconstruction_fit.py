"""Section 7 tests 6-8: the fits themselves, and the softening they must respect.

The parametric case has to recover truth before the high-dimensional runs are
worth attempting -- if the small case does not work, the big one will not
either. That ordering is why these live in their own module and run after the
operator tests.

All three are marked ``slow``: they cost 38 s, 41 s and 28 s on the CPU
backend, which is a gradient-descent fit and not a unit test's worth of time.
The CI smoke subset (``-m "not slow and not experimental"``) therefore skips
them, and the full tier runs them.

All three fits pin the topology for their epoch (``rebuild_cadence`` equal to
the iteration count) **except test 7**, which is specifically about the rebuilt
path. Pinning where the rebuild is not the subject buys ``jit_within_epoch``,
which turns a 150-second CPU fit into a 15-second one; the switching machinery
has its own tests in ``test_density_reconstruction_core.py``.
"""

import numpy as np
import pytest

from jaccpot.applications.density_reconstruction import (
    make_forward_operator,
    make_ground_truth,
)
from jaccpot.applications.density_reconstruction.diagnostics import field_residual
from jaccpot.applications.density_reconstruction.fit import FitConfig, run_fit
from jaccpot.applications.density_reconstruction.loss import Regularization
from jaccpot.applications.density_reconstruction.parameterize import (
    initial_positions,
    make_parameterization,
)
from jaccpot.applications.density_reconstruction.truth import TruthConfig

SOFTENING = 1.0e-2


def _truth(n, m, *, seed=0, **overrides):
    """A tiny seeded truth with observations generated by jaccpot."""
    config = TruthConfig(
        num_particles=n,
        num_tracers=m,
        seed=seed,
        softening=SOFTENING,
        generating_order=6,
        generating_theta=0.4,
        generating_leaf_size=16,
        **overrides,
    )
    return config, make_ground_truth(config)


def _operator(config, truth):
    """The observation operator matching a truth configuration."""
    return make_forward_operator(
        tracer_positions=truth.tracer_positions,
        source_mass=truth.source_mass,
        num_sources=int(config.num_particles),
        softening=config.softening,
        order=6,
        theta=0.4,
        leaf_size=16,
    )


def _min_pair_distance(positions):
    """Exact all-pairs minimum separation. Only for the tiny N used here."""
    x = np.asarray(positions, dtype=np.float64)
    delta = x[:, None, :] - x[None, :, :]
    d = np.sqrt(np.sum(delta**2, axis=-1))
    np.fill_diagonal(d, np.inf)
    return float(d.min())


# 6 -----------------------------------------------------------------------------
@pytest.mark.slow
def test_recovers_parametric_truth_noiseless():
    """The gate on everything downstream: the 7-parameter fit finds truth.

    Noiseless, no regularisation, every parameter started 0.1 away from its true
    value -- which for the three log scales is a 10.5% error in the scale itself,
    and for the tilts and the flattening an absolute offset. If this does not
    converge, no high-dimensional run is interpretable.
    """
    config, truth = _truth(160, 80)
    operator = _operator(config, truth)
    parameterization = make_parameterization("parametric", config=config)
    true_values = {k: float(v) for k, v in parameterization.true_params(config).items()}
    start = {name: value + 0.1 for name, value in true_values.items()}

    iterations = 400
    result = run_fit(
        operator=operator,
        observed=truth.observed_accelerations,
        parameterization=parameterization,
        initial_params=parameterization.pack(start),
        config=FitConfig(
            num_iterations=iterations,
            learning_rate=0.02,
            rebuild_cadence=iterations,
            jit_within_epoch=True,
            regularization=Regularization.none(),
            history_every=iterations,
        ),
    )

    assert parameterization.num_free == 7, "no perturber, so 7 free parameters"
    assert result.final_loss < result.initial_loss

    errors = {
        name: abs(float(result.params[name]) - true_values[name])
        for name in parameterization.names
    }
    worst = max(errors.values())
    assert worst < 1.0e-2, f"parametric fit did not recover truth: {errors}"
    # And the loss really did collapse, not merely improve.
    assert (
        result.final_loss < 1.0e-6 * result.initial_loss
    ), f"loss {result.initial_loss:.3e} -> {result.final_loss:.3e}"


# 7 -----------------------------------------------------------------------------
@pytest.mark.slow
def test_field_residual_decreases_positions():
    """The high-dimensional fit reduces the field residual, through rebuilds.

    ``rebuild_cadence = 1`` deliberately: this is the one test whose subject is
    the per-iteration-rebuild path, so it must not pin the topology. The
    assertion is on the **field residual**, the section's primary metric, and
    not on density agreement or position error -- which the section explicitly
    does not claim to recover.
    """
    config, truth = _truth(192, 96)
    operator = _operator(config, truth)
    parameterization = make_parameterization("positions", config=config)
    start = initial_positions(
        truth.source_positions, mode="perturbed_truth", seed=3, perturbation=0.05
    )

    before = field_residual(operator.evaluate(start), truth.observed_accelerations)

    result = run_fit(
        operator=operator,
        observed=truth.observed_accelerations,
        parameterization=parameterization,
        initial_params=parameterization.pack(start),
        config=FitConfig(
            num_iterations=8,
            learning_rate=2.0e-3,
            rebuild_cadence=1,
            regularization=Regularization.none(),
            history_every=1,
        ),
    )

    after = field_residual(
        operator.evaluate(result.positions), truth.observed_accelerations
    )

    assert parameterization.num_free == 3 * 192
    assert (
        after["rel_l2"] < before["rel_l2"]
    ), f"field residual did not fall: {before['rel_l2']:.4e} -> {after['rel_l2']:.4e}"
    assert result.final_loss < result.initial_loss
    # Every iteration rebuilt, so the switch log saw one state per iteration.
    assert result.switch_summary is not None
    assert result.switch_summary["extensive"]["observations"] == 8
    # The intensive rates exist and are rates, not counts.
    mean = result.switch_summary["intensive"]["mean"]
    assert 0.0 <= mean["slot_churn"] <= 1.0
    assert 0.0 <= mean["near_pair_churn"] <= 1.0
    # Every history row records whether it rebuilt, so a figure can mark them.
    assert all(row["rebuilt"] for row in result.history)


